const { withAppBuildGradle } = require("@expo/config-plugins");

const startMarker = "// @generated by with-workspace-bundle-inputs";

function addWorkspaceBundleInputs(contents) {
  if (contents.includes(startMarker)) return contents;

  const reactBlock = "react {\n";
  if (!contents.includes(reactBlock)) {
    throw new Error("Could not find the React Android block while adding workspace bundle inputs");
  }

  const workspaceInputs = `${reactBlock}    ${startMarker}
    tasks.withType(com.facebook.react.tasks.BundleHermesCTask).configureEach { task ->
        task.inputs.files(fileTree("\${rootDir}/../../../packages") {
            include "**/*.js", "**/*.jsx", "**/*.ts", "**/*.tsx", "**/*.json"
            exclude "**/build/**", "**/dist/**", "**/node_modules/**", "**/.turbo/**"
        })
        task.inputs.files(
            file("\${rootDir}/../../../package.json"),
            file("\${rootDir}/../../../pnpm-lock.yaml"),
            file("\${rootDir}/../metro.config.cjs")
        )
    }
`;

  return contents.replace(reactBlock, workspaceInputs);
}

function withWorkspaceBundleInputs(config) {
  return withAppBuildGradle(config, (gradleConfig) => {
    if (gradleConfig.modResults.language !== "groovy") {
      throw new Error("Loomarr's workspace bundle inputs expect a Groovy app build file");
    }
    gradleConfig.modResults.contents = addWorkspaceBundleInputs(gradleConfig.modResults.contents);
    return gradleConfig;
  });
}

module.exports = withWorkspaceBundleInputs;
module.exports.addWorkspaceBundleInputs = addWorkspaceBundleInputs;
